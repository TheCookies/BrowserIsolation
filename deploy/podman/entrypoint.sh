#!/usr/bin/env bash
# Container entrypoint: bootstrap /config/.env once, then start the app.
set -euo pipefail

CONFIG_DIR="${CONFIG_DIR:-/config}"
ENV_FILE="${ENV_FILE:-${CONFIG_DIR}/.env}"
DATA_DIR="${DATA_DIR:-/data}"

detect_ip() {
  local ip=""
  if command -v ip >/dev/null 2>&1; then
    ip="$(ip -4 -o addr show dev eth0 scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -n1 || true)"
    if [[ -z "${ip}" ]]; then
      ip="$(ip -4 -o addr show scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -n1 || true)"
    fi
  fi
  if [[ -z "${ip}" ]]; then
    ip="$(hostname -I 2>/dev/null | awk '{print $1}' || true)"
  fi
  echo "${ip:-127.0.0.1}"
}

random_password() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 18 | tr -d '\n=' | head -c 24
    return
  fi
  # Fallback: /dev/urandom hex
  head -c 18 /dev/urandom | od -An -tx1 | tr -d ' \n' | head -c 24
}

mkdir -p "${DATA_DIR}"
mkdir -p "${CONFIG_DIR}" 2>/dev/null || true

if [[ ! -f "${ENV_FILE}" ]]; then
  # Compose/local often injects env already — do not invent a conflicting /config/.env.
  if [[ -n "${PUBLIC_IP:-}" || -n "${AUTH_USERS:-}" || "${SKIP_CONFIG_BOOTSTRAP:-}" == "1" ]]; then
    echo "Using process environment (no ${ENV_FILE})"
  elif [[ ! -d "${CONFIG_DIR}" || ! -w "${CONFIG_DIR}" ]]; then
    echo "WARN: ${CONFIG_DIR} not writable; starting with process environment"
  else
  PUBLIC_IP_VALUE="${PUBLIC_IP:-$(detect_ip)}"
  ADMIN_PASSWORD_VALUE="${ADMIN_PASSWORD:-$(random_password)}"

  umask 077
  cat > "${ENV_FILE}" <<EOF
# Generated by container entrypoint on first start — $(date -u +%Y-%m-%dT%H:%MZ)
# This file is mounted from the host. Re-creating the container will NOT overwrite it.
PORT=8080
HOST=0.0.0.0
TRUST_PROXY=false
COOKIE_SECURE=false
SESSION_TTL_HOURS=24
BCRYPT_ROUNDS=12
DATABASE_PATH=/data/rbi.sqlite
STATIC_DIR=/app/web/dist
NODE_ENV=production
AUTH_USERS=admin:${ADMIN_PASSWORD_VALUE}:admin
SAML_ENABLED=false
ENABLED_BROWSERS=google-chrome,firefox,brave
NEKO_IMAGE_TAG=latest
PERSIST_PROFILES_ENABLED=true
ALLOW_CLIPBOARD=false
ALLOW_DOWNLOADS=false
LOCAL_WORKER_ENABLED=true
# Must match deploy/podman/install-worker.sh for self-enrolling workers.
WORKER_ENROLL_TOKEN=rbi_enroll_k9m2Vx7Qp4Hs8nWc3YfL6tZa1Bd0EgR5
BROWSER_NETWORK=rbi-browsers
# host: WebRTC binds on the host (required for Podman + Hyper-V Default Switch)
BROWSER_NETWORK_MODE=host
BROWSER_SHM_SIZE=2gb
BROWSER_CPUS=3
BROWSER_MEMORY=2g
DOCKER_SOCKET=/run/podman/podman.sock
PUBLIC_IP=${PUBLIC_IP_VALUE}
WEBRTC_PORT_RANGE=52000-52099
WEBRTC_ICELITE=true
ICE_SERVERS_FRONTEND=[]
ICE_SERVERS_BACKEND=[]
DESKTOP_SCREEN=1280x720@30
CAPTURE_VIDEO_CODEC=h264
IDLE_TIMEOUT_MINUTES=60
MAX_SESSION_HOURS=12
REAPER_INTERVAL_SECONDS=60
EOF
  chmod 600 "${ENV_FILE}"

  echo "============================================================"
  echo "Created ${ENV_FILE}"
  echo "PUBLIC_IP=${PUBLIC_IP_VALUE}"
  echo "Portal login user: admin"
  echo "Portal admin password: ${ADMIN_PASSWORD_VALUE}"
  echo "Save this password. It will not be shown again."
  echo "============================================================"
  fi
else
  echo "Using existing settings: ${ENV_FILE}"
fi

if [[ -f "${ENV_FILE}" ]]; then
  set -a
  # shellcheck disable=SC1090
  source "${ENV_FILE}"
  set +a
fi

export HOST="${HOST:-0.0.0.0}"
export PORT="${PORT:-8080}"
export DATABASE_PATH="${DATABASE_PATH:-/data/rbi.sqlite}"
export STATIC_DIR="${STATIC_DIR:-/app/web/dist}"
export NODE_ENV="${NODE_ENV:-production}"
export DOCKER_SOCKET="${DOCKER_SOCKET:-/var/run/docker.sock}"

cd /app/orchestrator

role="${RBI_ROLE:-orchestrator}"
if [[ "${role}" == "worker" ]]; then
  exec node dist/worker-main.js "$@"
fi

if [[ $# -gt 0 ]]; then
  exec "$@"
fi

exec node dist/index.js
