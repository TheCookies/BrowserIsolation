#!/usr/bin/env bash
# Browser Isolation — one-shot Alma/RHEL Podman installer / updater
#
# First install:
#   sudo podman login ghcr.io -u USER
#   sudo podman pull ghcr.io/thecookies/browserisolation:latest
#   sudo podman run --rm --entrypoint cat \
#     ghcr.io/thecookies/browserisolation:latest /deploy/install.sh | sudo bash
#
# Later updates (keeps your existing /etc/browser-isolation/browser-isolation.env):
#   same command again, or:  sudo systemctl restart browser-isolation.service
#
# Optional first-install overrides:
#   PUBLIC_IP=1.2.3.4 ADMIN_PASSWORD='secret' bash install.sh
#
# Force rewrite settings (destructive):
#   FORCE_SETTINGS=1 ADMIN_PASSWORD='secret' bash install.sh

set -euo pipefail

IMAGE="${IMAGE:-ghcr.io/thecookies/browserisolation:latest}"
ENV_FILE="/etc/browser-isolation/browser-isolation.env"
UNIT_DIR="/etc/containers/systemd"
AUTH_FILE="${AUTH_FILE:-/etc/containers/auth.json}"
FORCE_SETTINGS="${FORCE_SETTINGS:-0}"

die() { echo "ERROR: $*" >&2; exit 1; }
need_root() { [[ ${EUID:-$(id -u)} -eq 0 ]] || die "Run as root (sudo)."; }

# Prefer eth0 IPv4. Fallbacks: first non-loopback IPv4, then 127.0.0.1.
detect_ip() {
  local ip=""
  if command -v ip >/dev/null 2>&1; then
    ip="$(ip -4 -o addr show dev eth0 scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -n1 || true)"
    if [[ -z "${ip}" ]]; then
      ip="$(ip -4 -o addr show scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -n1 || true)"
    fi
  fi
  if [[ -z "${ip}" ]]; then
    ip="$(hostname -I 2>/dev/null | awk '{print $1}' || true)"
  fi
  echo "${ip:-127.0.0.1}"
}

# When this script is piped into bash, stdin is the script — prompts must use the TTY.
ask_secret() {
  local prompt="$1"
  local reply=""
  if [[ -r /dev/tty ]]; then
    # shellcheck disable=SC2162
    read -r -s -p "${prompt}" reply </dev/tty || true
    echo >/dev/tty
  fi
  printf '%s' "${reply}"
}

env_get() {
  local key="$1"
  local file="$2"
  awk -F= -v k="${key}" '
    $0 ~ "^" k "=" {
      sub(/^[^=]*=/, "", $0)
      print $0
      exit
    }
  ' "${file}" 2>/dev/null || true
}

need_root

echo "==> Browser Isolation installer"
echo "    Image: ${IMAGE}"

if ! command -v podman >/dev/null 2>&1; then
  echo "==> Installing podman"
  if command -v dnf >/dev/null 2>&1; then
    dnf install -y podman
  elif command -v yum >/dev/null 2>&1; then
    yum install -y podman
  else
    die "podman not found and no dnf/yum available"
  fi
fi

echo "==> Enabling podman.socket"
systemctl enable --now podman.socket
[[ -S /run/podman/podman.sock ]] || die "podman.socket did not create /run/podman/podman.sock"

# Systemd/Quadlet cannot see a normal interactive login (often stored under /run).
# Always use a persistent auth file that the service can read.
if [[ ! -f "${AUTH_FILE}" ]]; then
  echo
  echo "Missing ${AUTH_FILE}"
  echo "Log in once with a persistent auth file, then re-run:"
  echo
  echo "  read -s GHCR_TOKEN"
  echo "  echo \"\$GHCR_TOKEN\" | sudo podman login ghcr.io -u YOUR_GITHUB_USERNAME \\"
  echo "    --authfile ${AUTH_FILE} --password-stdin"
  echo "  unset GHCR_TOKEN"
  echo "  sudo chmod 600 ${AUTH_FILE}"
  echo
  die "GHCR auth file required for private pulls under systemd"
fi

if ! podman pull --authfile "${AUTH_FILE}" "${IMAGE}"; then
  echo
  echo "Could not pull ${IMAGE} with ${AUTH_FILE}"
  echo "Re-login:"
  echo "  echo \"\$GHCR_TOKEN\" | sudo podman login ghcr.io -u YOUR_GITHUB_USERNAME \\"
  echo "    --authfile ${AUTH_FILE} --password-stdin"
  echo
  die "pull failed (bad token, SSO not authorized, or image not published)"
fi
echo "==> Image pulled (authfile=${AUTH_FILE})"

mkdir -p /etc/browser-isolation "${UNIT_DIR}"

EXISTING_SETTINGS=0
if [[ -f "${ENV_FILE}" && "${FORCE_SETTINGS}" != "1" ]]; then
  EXISTING_SETTINGS=1
  PUBLIC_IP="$(env_get PUBLIC_IP "${ENV_FILE}")"
  PUBLIC_IP="${PUBLIC_IP:-$(detect_ip)}"
  echo "==> Keeping existing settings: ${ENV_FILE}"
  echo "    (set FORCE_SETTINGS=1 to rewrite — this would reset PUBLIC_IP / AUTH_USERS)"
else
  if [[ -z "${PUBLIC_IP:-}" ]]; then
    PUBLIC_IP="$(detect_ip)"
  fi
  echo "==> PUBLIC_IP=${PUBLIC_IP} (from eth0 IPv4, or override with PUBLIC_IP=...)"

  if [[ -z "${ADMIN_PASSWORD:-}" ]]; then
    echo "Set the Browser Isolation web login password for user 'admin'."
    echo "(This is NOT your Linux root password.)"
    ADMIN_PASSWORD="$(ask_secret "Portal admin password: ")"
  fi
  [[ -n "${ADMIN_PASSWORD}" ]] || die "portal admin password required (or set ADMIN_PASSWORD=...)"

  umask 077
  cat > "${ENV_FILE}" <<EOF
# Generated by deploy/podman/install.sh — $(date -u +%Y-%m-%dT%H:%MZ)
# Re-running install.sh will NOT overwrite this file unless FORCE_SETTINGS=1.
PORT=8080
TRUST_PROXY=false
COOKIE_SECURE=false
SESSION_TTL_HOURS=24
BCRYPT_ROUNDS=12
DATABASE_PATH=/data/rbi.sqlite
AUTH_USERS=admin:${ADMIN_PASSWORD}:admin
SAML_ENABLED=false
ENABLED_BROWSERS=google-chrome,firefox,brave
NEKO_IMAGE_TAG=latest
PERSIST_PROFILES_ENABLED=true
ALLOW_CLIPBOARD=false
ALLOW_DOWNLOADS=false
LOCAL_WORKER_ENABLED=true
# Must match deploy/podman/install-worker.sh for self-enrolling workers.
WORKER_ENROLL_TOKEN=rbi_enroll_k9m2Vx7Qp4Hs8nWc3YfL6tZa1Bd0EgR5
BROWSER_NETWORK=rbi-browsers
BROWSER_SHM_SIZE=2gb
BROWSER_CPUS=3
BROWSER_MEMORY=2g
DOCKER_SOCKET=/var/run/docker.sock
PUBLIC_IP=${PUBLIC_IP}
WEBRTC_PORT_RANGE=52000-52099
WEBRTC_ICELITE=true
ICE_SERVERS_FRONTEND=[]
ICE_SERVERS_BACKEND=[]
DESKTOP_SCREEN=1280x720@30
CAPTURE_VIDEO_CODEC=vp8
IDLE_TIMEOUT_MINUTES=60
MAX_SESSION_HOURS=12
REAPER_INTERVAL_SECONDS=60
EOF
  chmod 600 "${ENV_FILE}"
  echo "==> Wrote ${ENV_FILE}"
fi

cat > "${UNIT_DIR}/rbi-browsers.network" <<'EOF'
[Unit]
Description=Browser Isolation Podman network

[Network]
Label=app=browser-isolation
EOF

cat > "${UNIT_DIR}/rbi-data.volume" <<'EOF'
[Unit]
Description=Browser Isolation SQLite data volume

[Volume]
Label=app=browser-isolation
EOF

cat > "${UNIT_DIR}/browser-isolation.container" <<EOF
[Unit]
Description=Browser Isolation orchestrator (single-node + local worker)
After=network-online.target podman.socket
Wants=network-online.target podman.socket

[Container]
Image=${IMAGE}
Pull=always
AuthFile=${AUTH_FILE}
ContainerName=browser-isolation
HostName=browser-isolation
PublishPort=8080:8080
PublishPort=52000-52099:52000-52099/tcp
PublishPort=52000-52099:52000-52099/udp
EnvironmentFile=${ENV_FILE}
Environment=HOST=0.0.0.0
Environment=PORT=8080
Environment=DATABASE_PATH=/data/rbi.sqlite
Environment=STATIC_DIR=/app/web/dist
Environment=NODE_ENV=production
Environment=LOCAL_WORKER_ENABLED=true
Environment=DOCKER_SOCKET=/var/run/docker.sock
Volume=rbi-data.volume:/data
Volume=/run/podman/podman.sock:/var/run/docker.sock
Network=rbi-browsers.network
PodmanArgs=--init

[Service]
Restart=always
TimeoutStartSec=300

[Install]
WantedBy=multi-user.target
EOF

echo "==> Wrote Quadlet units in ${UNIT_DIR}"

# Quadlet units are generated — do not systemctl enable (Alma/RHEL rejects that).
# WantedBy=multi-user.target makes them start on boot after daemon-reload.
systemctl daemon-reload
if systemctl cat browser-isolation.service >/dev/null 2>&1; then
  systemctl restart browser-isolation.service
else
  die "browser-isolation.service was not generated. Check: ls ${UNIT_DIR} && journalctl -u podman* -xe"
fi

if command -v firewall-cmd >/dev/null 2>&1 && systemctl is-active --quiet firewalld; then
  echo "==> Opening firewall ports"
  firewall-cmd --permanent --add-port=8080/tcp >/dev/null
  firewall-cmd --permanent --add-port=52000-52099/tcp >/dev/null
  firewall-cmd --permanent --add-port=52000-52099/udp >/dev/null
  firewall-cmd --reload >/dev/null
fi

echo "==> Waiting for health"
ok=0
for _ in $(seq 1 60); do
  if curl -fsS "http://127.0.0.1:8080/api/health" >/dev/null 2>&1; then
    ok=1
    break
  fi
  sleep 2
done

echo
if [[ "${ok}" -eq 1 ]]; then
  echo "DONE. Open:  http://${PUBLIC_IP}:8080"
  if [[ "${EXISTING_SETTINGS}" -eq 1 ]]; then
    echo "Settings:    kept existing ${ENV_FILE}"
  else
    echo "Login:       admin / (password you set)"
  fi
  echo
  echo "Easy update later (keeps settings):"
  echo "  sudo systemctl restart browser-isolation.service"
  echo "  # or re-run this installer — it will not overwrite ${ENV_FILE}"
else
  echo "Service started but health check did not pass yet."
  echo "Check: sudo systemctl status browser-isolation.service"
  echo "Logs:  sudo journalctl -u browser-isolation.service -e"
  exit 1
fi
